package com.diyarsari.transfer.controller;

import com.diyarsari.transfer.dto.TransferRequest;
import com.diyarsari.transfer.dto.TransferResponse;
import com.diyarsari.transfer.service.TransferResult;
import com.diyarsari.transfer.service.TransferService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Size;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestHeader;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;
import org.springframework.web.servlet.support.ServletUriComponentsBuilder;

import java.util.UUID;

@Tag(name = "Transfers")
@RestController
@RequestMapping("/api/transfers")
public class TransferController {

    public static final String IDEMPOTENCY_KEY = "Idempotency-Key";
    public static final String IDEMPOTENT_REPLAYED = "Idempotent-Replayed";

    private final TransferService transferService;

    public TransferController(TransferService transferService) {
        this.transferService = transferService;
    }

    @Operation(summary = "Transfer money between two accounts",
            description = """
                    Requires an Idempotency-Key header (for example a UUID generated by the client).
                    Repeating the call with the same key and body returns the original transfer and moves no money \
                    (response header Idempotent-Replayed: true). Reusing a key with a different body returns 422.
                    Business rejections (insufficient funds, currency mismatch) are stored and returned with status REJECTED.""")
    @PostMapping
    public ResponseEntity<TransferResponse> create(
            @Parameter(description = "Unique key per logical transfer, e.g. a UUID", required = true)
            @RequestHeader(IDEMPOTENCY_KEY) @NotBlank @Size(max = 100) String idempotencyKey,
            @Valid @RequestBody TransferRequest request) {
        TransferResult result = transferService.transfer(idempotencyKey, request);
        var location = ServletUriComponentsBuilder.fromCurrentRequest().path("/{id}")
                .buildAndExpand(result.transfer().id()).toUri();
        return ResponseEntity.created(location)
                .header(IDEMPOTENT_REPLAYED, String.valueOf(result.replayed()))
                .body(result.transfer());
    }

    @Operation(summary = "Get a transfer by id")
    @GetMapping("/{id}")
    public TransferResponse get(@PathVariable UUID id) {
        return transferService.get(id);
    }
}
