CREATE TABLE accounts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number  VARCHAR(34)    NOT NULL,
    owner_name      VARCHAR(100)   NOT NULL,
    currency        VARCHAR(3)     NOT NULL,
    balance         NUMERIC(19, 2) NOT NULL,
    opening_balance NUMERIC(19, 2) NOT NULL,
    version         BIGINT         NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT uk_accounts_account_number UNIQUE (account_number),
    -- Last line of defence: the database itself refuses an overdraft.
    CONSTRAINT ck_accounts_balance_non_negative CHECK (balance >= 0),
    CONSTRAINT ck_accounts_opening_balance_non_negative CHECK (opening_balance >= 0)
);

CREATE TABLE transfers (
    id              UUID PRIMARY KEY,
    idempotency_key VARCHAR(100)   NOT NULL,
    request_hash    VARCHAR(64)    NOT NULL,
    from_account_id BIGINT         NOT NULL REFERENCES accounts (id),
    to_account_id   BIGINT         NOT NULL REFERENCES accounts (id),
    amount          NUMERIC(19, 2) NOT NULL,
    currency        VARCHAR(3)     NOT NULL,
    description     VARCHAR(140),
    status          VARCHAR(16)    NOT NULL,
    failure_reason  VARCHAR(32),
    created_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),
    -- The heart of idempotency: one key can only ever produce one transfer.
    CONSTRAINT uk_transfers_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT ck_transfers_amount_positive CHECK (amount > 0),
    CONSTRAINT ck_transfers_distinct_accounts CHECK (from_account_id <> to_account_id),
    CONSTRAINT ck_transfers_status CHECK (status IN ('COMPLETED', 'REJECTED')),
    CONSTRAINT ck_transfers_failure_reason CHECK (
        (status = 'COMPLETED' AND failure_reason IS NULL) OR
        (status = 'REJECTED' AND failure_reason IS NOT NULL))
);

CREATE INDEX ix_transfers_from_account ON transfers (from_account_id);
CREATE INDEX ix_transfers_to_account ON transfers (to_account_id);

CREATE TABLE ledger_entries (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id   UUID           NOT NULL REFERENCES transfers (id),
    account_id    BIGINT         NOT NULL REFERENCES accounts (id),
    entry_type    VARCHAR(6)     NOT NULL,
    amount        NUMERIC(19, 2) NOT NULL,
    currency      VARCHAR(3)     NOT NULL,
    balance_after NUMERIC(19, 2) NOT NULL,
    created_at    TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT ck_ledger_entries_type CHECK (entry_type IN ('DEBIT', 'CREDIT')),
    CONSTRAINT ck_ledger_entries_amount_positive CHECK (amount > 0),
    -- Exactly one DEBIT and one CREDIT per transfer.
    CONSTRAINT uk_ledger_entries_transfer_type UNIQUE (transfer_id, entry_type)
);

CREATE INDEX ix_ledger_entries_account ON ledger_entries (account_id, id DESC);
